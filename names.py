def tithi_name(lang, idx):
    """idx 0..29 -> (paksha label, tithi name)."""
    p = 0 if idx < 15 else 1
    o = idx % 15
    nm = TITHI[lang][o] if o != 14 else (PURNIMA[lang] if p == 0 else AMAVASYA[lang])
    return PAKSHA[lang][p], nm


def month_name(lang, p):
    """Solar month for ta/bn/ml, amanta lunar month for the rest."""
    if lang in SOLAR_MONTH:
        return SOLAR_MONTH[lang][p["surya_rashi"]]
    return MASA[lang][p["masa"]]
